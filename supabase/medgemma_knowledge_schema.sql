create table metadata (key text primary key, value text not null);
create table injury_types (code text primary key, name_vi text not null, coverage_note text not null);
create table sources (
    id text primary key, title text not null, authors text not null,
    publisher text not null, source_type text not null,
    publication_date text, last_reviewed_date text, evidence_search_date text,
    doi text, url text not null, limitations text not null
);
create table source_files (
    id text primary key, source_id text not null references sources(id),
    relative_path text not null unique, sha256 text not null check (length(sha256) = 64),
    page_count integer not null check (page_count > 0), language text not null,
    variant text not null check (variant in ('original', 'unreviewed_translation')),
    note text not null
);
create table knowledge_entries (
    id bigint generated by default as identity primary key,
    slug text not null, version integer not null check (version > 0),
    title text not null, summary text not null,
    applicability text not null check (length(trim(applicability)) > 0),
    exclusions text not null check (length(trim(exclusions)) > 0),
    review_notes text not null,
    status text not null default 'draft' check (status in ('draft', 'in_review', 'approved', 'retired')),
    reviewer text, reviewed_at text, review_note text,
    created_at text not null default to_char(clock_timestamp() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    unique (slug, version),
    check (status not in ('approved', 'retired') or (
        length(trim(coalesce(reviewer, ''))) > 0 and
        length(trim(coalesce(reviewed_at, ''))) > 0 and
        length(trim(coalesce(review_note, ''))) > 0
    ))
);
create index idx_entries_status_slug on knowledge_entries (status, slug, version);
create table entry_injury_types (
    entry_id bigint not null references knowledge_entries(id),
    injury_code text not null references injury_types(code),
    primary key (entry_id, injury_code)
);
create table care_steps (
    id bigint generated by default as identity primary key,
    entry_id bigint not null references knowledge_entries(id),
    step_number integer not null check (step_number > 0), instruction text not null,
    unique (entry_id, step_number)
);
create table warnings (
    id bigint generated by default as identity primary key,
    entry_id bigint not null references knowledge_entries(id),
    severity text not null check (severity in ('emergency', 'seek_care', 'avoid', 'caution')),
    description text not null, action text not null
);
create index idx_warnings_entry on warnings (entry_id);
create table entry_citations (
    id bigint generated by default as identity primary key,
    entry_id bigint not null references knowledge_entries(id),
    file_id text not null references source_files(id),
    pdf_page_start integer not null check (pdf_page_start > 0),
    pdf_page_end integer not null check (pdf_page_end >= pdf_page_start),
    printed_pages text not null, section text not null,
    role text not null check (role in ('primary', 'supporting', 'translation')),
    recommendation_class text, evidence_level text, interpretation_note text not null
);
create index idx_citations_entry on entry_citations (entry_id);
create table evidence_summaries (
    id text primary key, file_id text not null references source_files(id),
    pdf_page_start integer not null, pdf_page_end integer not null,
    question text not null, finding text not null, certainty text not null,
    applicability_limit text not null,
    check (pdf_page_start > 0 and pdf_page_end >= pdf_page_start)
);
create table coverage_gaps (
    id text primary key, injury_code text references injury_types(code),
    description text not null, required_action text not null,
    status text not null default 'open' check (status in ('open', 'resolved'))
);
create table review_history (
    id bigint generated by default as identity primary key,
    entry_id bigint not null references knowledge_entries(id),
    old_status text not null, new_status text not null, reviewer text, review_note text,
    changed_at text not null default to_char(clock_timestamp() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
create table review_documents (name text primary key, content jsonb not null);

create view published_entries as
select e.* from knowledge_entries e
where e.status = 'approved' and not exists (
    select 1 from knowledge_entries newer
    where newer.slug = e.slug and newer.status = 'approved' and newer.version > e.version
);
create view published_injury_types as
select t.* from entry_injury_types t join published_entries e on e.id = t.entry_id;
create view published_steps as
select s.* from care_steps s join published_entries e on e.id = s.entry_id;
create view published_warnings as
select w.* from warnings w join published_entries e on e.id = w.entry_id;
create view published_citations as
select c.*, f.relative_path, f.sha256, f.language, f.variant, src.title as source_title, src.doi, src.url
from entry_citations c join published_entries e on e.id = c.entry_id
join source_files f on f.id = c.file_id join sources src on src.id = f.source_id;

create function check_approval(entry knowledge_entries) returns void
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
begin
    begin
        if entry.reviewed_at is null or not isfinite(entry.reviewed_at::timestamptz) then
            raise check_violation using message = 'Approval requires a valid review timestamp';
        end if;
    exception when invalid_datetime_format or datetime_field_overflow then
        raise check_violation using message = 'Approval requires a valid review timestamp';
    end;
    if not exists (
        select 1 from entry_citations c join source_files f on f.id = c.file_id
        where c.entry_id = entry.id and c.role = 'primary' and f.variant = 'original'
    ) or not exists (select 1 from care_steps where entry_id = entry.id)
      or not exists (select 1 from warnings where entry_id = entry.id)
      or not exists (select 1 from entry_injury_types where entry_id = entry.id) then
        raise check_violation using message = 'Approval requires an original source, care steps, warnings and an injury group';
    end if;
end;
$$;

create function guard_knowledge_entry() returns trigger
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
begin
    if tg_op = 'INSERT' then
        if new.status not in ('draft', 'in_review') then
            raise check_violation using message = 'Create a draft, then review before approval';
        end if;
        return new;
    end if;
    if tg_op = 'DELETE' then
        if old.status in ('approved', 'retired') then
            raise check_violation using message = 'Retain reviewed versions for audit';
        end if;
        return old;
    end if;
    if old.status in ('approved', 'retired')
       and (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
        raise check_violation using message = 'Approved content is immutable';
    end if;
    if new.status <> old.status then
        if not (
            (old.status = 'draft' and new.status in ('in_review', 'approved')) or
            (old.status = 'in_review' and new.status in ('draft', 'approved')) or
            (old.status = 'approved' and new.status = 'retired')
        ) then
            raise check_violation using message = 'Invalid review status transition';
        end if;
        if new.status = 'approved' then
            perform check_approval(new);
        end if;
    end if;
    return new;
end;
$$;
create trigger entries_guard before insert or update or delete on knowledge_entries
for each row execute function guard_knowledge_entry();

create function audit_entry_status() returns trigger
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
begin
    insert into review_history (entry_id, old_status, new_status, reviewer, review_note)
    values (new.id, old.status, new.status, new.reviewer, new.review_note);
    return new;
end;
$$;
create trigger entries_audit after update of status on knowledge_entries
for each row when (new.status <> old.status) execute function audit_entry_status();

create function guard_reviewed_children() returns trigger
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
declare
    affected_ids bigint[];
    entry_status text;
begin
    if tg_op = 'INSERT' then
        affected_ids := array[new.entry_id];
    elsif tg_op = 'DELETE' then
        affected_ids := array[old.entry_id];
    else
        affected_ids := array[old.entry_id, new.entry_id];
    end if;
    for entry_status in
        select status from knowledge_entries where id = any(affected_ids) order by id for share
    loop
        if entry_status in ('approved', 'retired') then
            raise check_violation using message = 'Reviewed child content is immutable';
        end if;
    end loop;
    if tg_op = 'DELETE' then return old; end if;
    return new;
end;
$$;

create function guard_pdf_pages() returns trigger
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
begin
    if new.pdf_page_end > (select page_count from source_files where id = new.file_id) then
        raise check_violation using message = 'Citation is outside the PDF page range';
    end if;
    return new;
end;
$$;
create trigger citations_pages before insert or update on entry_citations
for each row execute function guard_pdf_pages();
create trigger evidence_pages before insert or update on evidence_summaries
for each row execute function guard_pdf_pages();

create function reject_provenance_change() returns trigger
language plpgsql set search_path to medgemma_kb, pg_catalog as $$
