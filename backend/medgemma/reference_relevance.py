"""Independent evidence from the original query limits reference candidates.

A model-generated document title is never evidence of query/source relevance.
These cues nominate references only; they do not diagnose an injury or severity.
"""
from knowledge_search import fold, query_topics, NEGATIONS


def mentioned(query, phrase):
    words, tokens = fold(query).split(), phrase.split()
    for start in range(len(words) - len(tokens) + 1):
        if words[start:start + len(tokens)] == tokens and not any(
                words[i] in NEGATIONS and not (i + 1 < start and words[i + 1] == 'biet')
                for i in range(max(0, start - 3), start)):
            return True
    return False


def reference_scope(query):
    positive, negative, _ = query_topics(query)
    topics = set(positive)
    wound_terms = ('vet thuong', 'vet can', 'bi can',
                   'tro da', 'troc da', 'da bi rach', 'rach da')
    if any(mentioned(query, phrase) for phrase in wound_terms):
        topics.update({'cut', 'graze'} - negative)
    body = any(mentioned(query, part) for part in ('tay', 'chan', 'da', 'dau goi', 'khuu tay'))
    bleeding = any(mentioned(query, phrase) for phrase in ('chay mau', 'cam mau'))
    if bleeding and ((body and not mentioned(query, 'chan rang')) or mentioned(query, 'mau ngoai')):
        topics.update({'cut', 'graze'} - negative)
    friction = any(mentioned(query, phrase) for phrase in
                   ('ca xuong duong', 'ca vao', 'co vao', 'quet vao', 'te xe', 'nga xe'))
    if body and friction:
        topics.update({'graze'} - negative)
    heat = any(mentioned(query, phrase) for phrase in ('nuoc nong do', 'nuoc nong tat', 'dau nong do'))
    if body and heat and 'thermal_burn' not in negative:
        topics.add('thermal_burn')
    general = any(mentioned(query, phrase) for phrase in
                  ('an toan hien truong', 'kiem tra dap ung', 'kiem tra ho hap',
                   'bat tinh', 'ngung tho', 'khong dap ung'))
    smoke = any(mentioned(query, phrase) for phrase in ('hit khoi', 'ngat khoi'))
    return topics, general, smoke


def is_wound_care_question(query):
    """Recognize a care action, without inferring an injury from the action alone."""
    text = fold(query)
    figurative = any(phrase in text for phrase in
                     ('vet thuong long', 'vet thuong tam hon', 'vet thuong tinh cam', 'vet thuong tinh yeu'))
    if figurative and not any(phrase in text for phrase in ('long ban tay', 'long ban chan')):
        return False
    return any(mentioned(query, action) for action in
               ('sat trung', 'khu trung', 'lam sach', 've sinh', 'rua',
                'bang vet', 'bang lai', 'thay bang', 'dan bang',
                'chay mau', 'cam mau', 'di vat', 'co mu', 'nhiem trung'))


def eligible_references(entries, query):
    topics, general, smoke = reference_scope(query)
    result = []
    for entry in entries:
        slug = entry.get('slug', '')
        title = fold(entry['title'])
        # A specific document request is independent evidence, unlike the title
        # generated by an AI selector after it has already chosen that document.
        explicit_title = len(title.split()) >= 4 and mentioned(query, title)
        if explicit_title:
            result.append(entry)
        elif slug == 'general-emergency':
            if general:
                result.append(entry)
        elif slug == 'smoke-inhalation-warning':
            if smoke:
                result.append(entry)
        elif slug == 'chemical-eye-first-aid':
            if 'chemical_burn' in topics and mentioned(query, 'mat'):
                result.append(entry)
        elif slug == 'chemical-skin-first-aid':
            eye = mentioned(query, 'mat')
            skin = any(mentioned(query, part) for part in ('tay', 'chan', 'da', 'lung'))
            if 'chemical_burn' in topics and (not eye or skin):
                result.append(entry)
        elif {item['code'] for item in entry['injury_types']} & topics:
            result.append(entry)
    return result
